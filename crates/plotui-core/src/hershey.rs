use crate::{Framebuffer, Rgb};

/// Capital-box height in font units (top of capitals to baseline).
const EM: f32 = HERSHEY_BASELINE - HERSHEY_TOP;

fn glyph(ch: char) -> Option<&'static HersheyGlyph> {
    let code = ch as usize;
    (0x20..=0x7E).contains(&code).then(|| &HERSHEY[code - 0x20])
}

/// Pixel advance width of `text` drawn at `cap_height` pixels.
/// Non-ASCII characters advance by the space width, as in the bitmap font.
pub fn hershey_text_width(text: &str, cap_height: f32) -> i32 {
    let units: i32 =
        text.chars().map(|ch| glyph(ch).map_or(HERSHEY[0].adv, |g| g.adv) as i32).sum();
    (units as f32 * cap_height / EM).ceil() as i32
}

/// Squared distance from `p` to the segment `a`–`b`.
fn seg_d2(p: (f32, f32), a: (f32, f32), b: (f32, f32)) -> f32 {
    let (abx, aby) = (b.0 - a.0, b.1 - a.1);
    let (apx, apy) = (p.0 - a.0, p.1 - a.1);
    let len2 = abx * abx + aby * aby;
    let t = if len2 > 0.0 { ((apx * abx + apy * aby) / len2).clamp(0.0, 1.0) } else { 0.0 };
    let (dx, dy) = (p.0 - (a.0 + abx * t), p.1 - (a.1 + aby * t));
    dx * dx + dy * dy
}

/// Draw `text` in the Hershey Simplex stroke font, antialiased against a known
/// opaque `bg` — for chrome that paints its own fill first, like the legend.
/// `(x, y)` is the top-left of the capital box and `cap_height` its pixel
/// height; descenders reach about a third of it further down. Strokes are
/// rasterized into a per-glyph coverage buffer (max over segments) and blitted
/// once, so crossing strokes cannot notch each other's cores.
#[allow(clippy::too_many_arguments)]
pub fn draw_text_hershey(
    fb: &mut Framebuffer,
    x: i32,
    y: i32,
    text: &str,
    cap_height: f32,
    z: f32,
    color: Rgb,
    bg: Rgb,
) {
    let scale = cap_height / EM;
    let halfw = (cap_height / 16.0).max(0.55);
    let reach = halfw + 1.0;
    let mut pen_x = x as f32;
    for ch in text.chars() {
        let Some(g) = glyph(ch) else {
            pen_x += HERSHEY[0].adv as f32 * scale;
            continue;
        };
        // Glyph strokes in pixel space.
        let px = |sx: i8, sy: i8| -> (f32, f32) {
            (pen_x + sx as f32 * scale, y as f32 + (sy as f32 - HERSHEY_TOP) * scale)
        };
        if !g.strokes.is_empty() {
            let (mut x0, mut y0) = (f32::INFINITY, f32::INFINITY);
            let (mut x1, mut y1) = (f32::NEG_INFINITY, f32::NEG_INFINITY);
            for s in g.strokes {
                for &(sx, sy) in *s {
                    let (gx, gy) = px(sx, sy);
                    x0 = x0.min(gx);
                    y0 = y0.min(gy);
                    x1 = x1.max(gx);
                    y1 = y1.max(gy);
                }
            }
            let bx0 = (x0 - reach).floor() as i32;
            let by0 = (y0 - reach).floor() as i32;
            let bw = ((x1 + reach).ceil() as i32 - bx0 + 1).max(1) as usize;
            let bh = ((y1 + reach).ceil() as i32 - by0 + 1).max(1) as usize;
            let mut cov = vec![0.0f32; bw * bh];
            for s in g.strokes {
                for w in s.windows(2) {
                    let a = px(w[0].0, w[0].1);
                    let b = px(w[1].0, w[1].1);
                    let sx0 = ((a.0.min(b.0) - reach).floor() as i32 - bx0).max(0);
                    let sy0 = ((a.1.min(b.1) - reach).floor() as i32 - by0).max(0);
                    let sx1 = (((a.0.max(b.0) + reach).ceil() as i32) - bx0).min(bw as i32 - 1);
                    let sy1 = (((a.1.max(b.1) + reach).ceil() as i32) - by0).min(bh as i32 - 1);
                    for cy in sy0..=sy1 {
                        for cx in sx0..=sx1 {
                            let p = ((bx0 + cx) as f32 + 0.5, (by0 + cy) as f32 + 0.5);
                            let d = seg_d2(p, a, b).sqrt();
                            let c = (halfw + 0.5 - d).clamp(0.0, 1.0);
                            let slot = &mut cov[cy as usize * bw + cx as usize];
                            *slot = slot.max(c);
                        }
                    }
                }
            }
            for cy in 0..bh {
                for cx in 0..bw {
                    let t = cov[cy * bw + cx];
                    if t <= 0.02 {
                        continue;
                    }
                    let c = [
                        (bg[0] as f32 + (color[0] as f32 - bg[0] as f32) * t) as u8,
                        (bg[1] as f32 + (color[1] as f32 - bg[1] as f32) * t) as u8,
                        (bg[2] as f32 + (color[2] as f32 - bg[2] as f32) * t) as u8,
                    ];
                    fb.put_px(bx0 + cx as i32, by0 + cy as i32, z, c);
                }
            }
        }
        pen_x += g.adv as f32 * scale;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn width_grows_with_text_and_size() {
        assert!(hershey_text_width("ab", 14.0) > hershey_text_width("a", 14.0));
        assert!(hershey_text_width("ab", 28.0) > hershey_text_width("ab", 14.0));
        assert_eq!(hershey_text_width("é", 14.0), hershey_text_width(" ", 14.0));
    }

    #[test]
    fn strokes_render_solid_cores_with_soft_edges() {
        let mut fb = Framebuffer::new(60, 40);
        draw_text_hershey(&mut fb, 4, 4, "Ay", 18.0, 0.0, [255, 255, 255], [0, 0, 0]);
        let mut solid = 0;
        let mut partial = 0;
        for p in fb.rgba().chunks(4) {
            if p[3] == 255 {
                if p[0] >= 250 {
                    solid += 1;
                } else {
                    partial += 1;
                }
            }
        }
        assert!(solid > 0, "no solid stroke cores");
        assert!(partial > solid / 4, "no antialiased edges: {partial} vs {solid}");
    }

    /// Crossing strokes ('t', '+') keep their cores solid: max-coverage
    /// accumulation, not last-write-wins.
    #[test]
    fn crossing_strokes_do_not_notch() {
        let mut fb = Framebuffer::new(40, 40);
        draw_text_hershey(&mut fb, 4, 4, "+", 20.0, 0.0, [255, 255, 255], [0, 0, 0]);
        // The cross centre must be fully lit.
        let rgba = fb.rgba();
        let max = rgba.chunks(4).filter(|p| p[3] == 255).map(|p| p[0]).max().unwrap();
        assert!(max >= 250, "cross centre washed out: {max}");
    }
}
