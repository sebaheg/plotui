/// Which grid vertex and axis each cell edge belongs to: the edge runs from
/// the cell corner `CORNER[base]` in direction `axis`. Two neighbouring
/// cells name a shared edge identically, so their vertices deduplicate and
/// normals smooth across the seam. Derived from the numbering above rather
/// than transcribed, so it cannot drift from it.
const EDGE_OWNER: [(usize, usize); 12] = edge_owners();

const fn edge_owners() -> [(usize, usize); 12] {
    let mut out = [(0usize, 0usize); 12];
    let mut e = 0;
    while e < 12 {
        let (a, b) = (EDGE_CORNERS[e][0], EDGE_CORNERS[e][1]);
        // The two corners differ in exactly one coordinate: the edge's axis.
        let mut axis = 0;
        while CORNER[a][axis] == CORNER[b][axis] {
            axis += 1;
        }
        out[e] = (if CORNER[a][axis] < CORNER[b][axis] { a } else { b }, axis);
        e += 1;
    }
    out
}

/// The iso-surface `field == iso` of a sampled scalar field, as an indexed
/// triangle mesh ready for [`crate::Plot::add_mesh3d`].
///
/// `values[(k * ny + j) * nx + i]` is the field at
/// `origin + [i, j, k] * cell`, so the grid is axis-aligned and uniform.
/// Vertices are placed by linear interpolation along the cut edges and
/// shared between neighbouring cells, which is what lets the renderer's
/// per-vertex normals smooth across cell boundaries. Cells with a
/// non-finite corner are skipped, like a surface's holes.
///
/// An undersized `values` yields an empty mesh rather than a panic — the
/// grid dimensions are the caller's claim about their own data.
pub fn marching_cubes(
    values: &[f32],
    nx: usize,
    ny: usize,
    nz: usize,
    origin: [f32; 3],
    cell: f32,
    iso: f32,
) -> (Vec<[f32; 3]>, Vec<[u32; 3]>) {
    let mut verts: Vec<[f32; 3]> = Vec::new();
    let mut tris: Vec<[u32; 3]> = Vec::new();
    if nx < 2 || ny < 2 || nz < 2 || values.len() < nx * ny * nz {
        return (verts, tris);
    }
    let at = |i: usize, j: usize, k: usize| values[(k * ny + j) * nx + i];
    let pos = |i: usize, j: usize, k: usize| {
        [origin[0] + i as f32 * cell, origin[1] + j as f32 * cell, origin[2] + k as f32 * cell]
    };
    // Vertex per shared grid edge, keyed by (grid vertex, axis).
    let mut shared: HashMap<usize, u32> = HashMap::new();
    let mut corner = [0.0f32; 8];
    let mut edge_vert = [0u32; 12];
    for k in 0..nz - 1 {
        for j in 0..ny - 1 {
            for i in 0..nx - 1 {
                let mut code = 0usize;
                for (c, off) in CORNER.iter().enumerate() {
                    let v = at(i + off[0], j + off[1], k + off[2]);
                    corner[c] = v;
                    if v < iso {
                        code |= 1 << c;
                    }
                }
                // A non-finite corner compares false against `iso` in both
                // directions; skip the cell outright instead of cutting it
                // against a value that has no sign.
                if EDGE_TABLE[code] == 0 || corner.iter().any(|v| !v.is_finite()) {
                    continue;
                }
                for e in 0..12 {
                    if EDGE_TABLE[code] & (1 << e) == 0 {
                        continue;
                    }
                    let (base, axis) = EDGE_OWNER[e];
                    let o = CORNER[base];
                    let (bi, bj, bk) = (i + o[0], j + o[1], k + o[2]);
                    let key = ((bk * ny + bj) * nx + bi) * 3 + axis;
                    edge_vert[e] = *shared.entry(key).or_insert_with(|| {
                        let (mut ei, mut ej, mut ek) = (bi, bj, bk);
                        match axis {
                            0 => ei += 1,
                            1 => ej += 1,
                            _ => ek += 1,
                        }
                        let (a, b) = (at(bi, bj, bk), at(ei, ej, ek));
                        // Both endpoints straddle `iso`, so the denominator
                        // is nonzero; guard the exactly-equal case anyway.
                        let d = b - a;
                        let t = if d.abs() > 1e-20 { (iso - a) / d } else { 0.5 };
                        let (p, q) = (pos(bi, bj, bk), pos(ei, ej, ek));
                        verts.push([
                            p[0] + (q[0] - p[0]) * t,
                            p[1] + (q[1] - p[1]) * t,
                            p[2] + (q[2] - p[2]) * t,
                        ]);
                        (verts.len() - 1) as u32
                    });
                }
                for t in TRI_TABLE[code].chunks(3) {
                    if t[0] < 0 {
                        break;
                    }
                    tris.push([
                        edge_vert[t[0] as usize],
                        edge_vert[t[1] as usize],
                        edge_vert[t[2] as usize],
                    ]);
                }
            }
        }
    }
    (verts, tris)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;

    const N: usize = 12;
    const CELL: f32 = 2.0 / (N - 1) as f32;
    const ORIGIN: [f32; 3] = [-1.0, -1.0, -1.0];

    /// Sample `f` over the N³ test grid.
    fn grid(f: impl Fn(f32, f32, f32) -> f32) -> Vec<f32> {
        let c = |i: usize| -1.0 + i as f32 * CELL;
        (0..N)
            .flat_map(|k| (0..N).flat_map(move |j| (0..N).map(move |i| (i, j, k))))
            .map(|(i, j, k)| f(c(i), c(j), c(k)))
            .collect()
    }

    /// A radius-0.6 sphere, well clear of the grid boundary.
    fn sphere() -> Vec<f32> {
        grid(|x, y, z| (x * x + y * y + z * z).sqrt() - 0.6)
    }

    #[test]
    fn sphere_surface_lands_on_the_sphere() {
        let (verts, tris) = marching_cubes(&sphere(), N, N, N, ORIGIN, CELL, 0.0);
        assert!(!verts.is_empty() && !tris.is_empty(), "empty mesh");
        for v in &verts {
            for k in 0..3 {
                assert!(v[k] >= -1.0 - 1e-5 && v[k] <= 1.0 + 1e-5, "{v:?} outside the grid");
            }
            let r = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
            // Linear interpolation of a curved field lands within a cell.
            assert!((r - 0.6).abs() < CELL, "vertex radius {r}");
        }
        for t in &tris {
            assert!(t.iter().all(|&i| (i as usize) < verts.len()), "index out of range");
        }
    }

    #[test]
    fn marching_cubes_is_deterministic() {
        let v = sphere();
        assert_eq!(
            marching_cubes(&v, N, N, N, ORIGIN, CELL, 0.0),
            marching_cubes(&v, N, N, N, ORIGIN, CELL, 0.0)
        );
    }

    /// The tables, checked as a whole: a closed surface built from shared
    /// edge vertices must be a consistently-wound closed manifold — every
    /// directed edge traversed exactly once, so every undirected edge is
    /// shared by exactly two triangles. A single mistranscribed table row
    /// leaves a dangling or doubled edge here.
    #[test]
    fn closed_fields_produce_watertight_meshes() {
        // Two blobs plus a wobble, so the sweep hits many of the 256 cases;
        // the field stays positive at the grid boundary, so the surface is
        // closed inside it.
        let fields = [
            sphere(),
            grid(|x, y, z| {
                let a = ((x - 0.3).powi(2) + y * y + z * z).sqrt() - 0.4;
                let b = ((x + 0.3).powi(2) + y * y + z * z).sqrt() - 0.35;
                a.min(b) + 0.06 * (7.0 * x).sin() * (7.0 * y).sin() * (7.0 * z).sin()
            }),
        ];
        for (f, field) in fields.iter().enumerate() {
            let (verts, tris) = marching_cubes(field, N, N, N, ORIGIN, CELL, 0.0);
            assert!(tris.len() > 100, "field {f}: only {} triangles", tris.len());
            let mut directed: HashMap<(u32, u32), usize> = HashMap::new();
            for t in &tris {
                for e in [(t[0], t[1]), (t[1], t[2]), (t[2], t[0])] {
                    *directed.entry(e).or_default() += 1;
                }
            }
            for (&(a, b), &n) in &directed {
                assert_eq!(n, 1, "field {f}: directed edge {a}→{b} used {n}×");
                assert_eq!(
                    directed.get(&(b, a)).copied().unwrap_or(0),
                    1,
                    "field {f}: edge {a}–{b} has no opposite twin",
                );
            }
            assert!(verts.len() < tris.len(), "field {f}: vertices were not shared");
        }
    }

    /// Nothing to cut: a field entirely on one side of `iso`, a degenerate
    /// grid, and a short `values` all yield an empty mesh.
    #[test]
    fn empty_inputs_yield_empty_meshes() {
        let ones = vec![1.0f32; N * N * N];
        assert_eq!(marching_cubes(&ones, N, N, N, ORIGIN, CELL, 0.0).1.len(), 0);
        assert_eq!(marching_cubes(&ones, 1, N, N, ORIGIN, CELL, 0.0).0.len(), 0);
        assert_eq!(marching_cubes(&[1.0, -1.0], N, N, N, ORIGIN, CELL, 0.0).0.len(), 0);
    }

    /// A NaN corner leaves its cells uncut, the way a surface leaves holes.
    #[test]
    fn non_finite_corners_become_holes() {
        let full = marching_cubes(&sphere(), N, N, N, ORIGIN, CELL, 0.0);
        let mut holed = sphere();
        // The grid vertex nearest the sphere's +x pole, so its cells are
        // ones the full sweep actually cut.
        let pole = (0..N).min_by(|&a, &b| {
            let d = |i: usize| ((-1.0 + i as f32 * CELL) - 0.6).abs();
            d(a).total_cmp(&d(b))
        });
        let (i, j, k) = (pole.expect("non-empty grid"), N / 2, N / 2);
        holed[(k * N + j) * N + i] = f32::NAN;
        let cut = marching_cubes(&holed, N, N, N, ORIGIN, CELL, 0.0);
        assert!(cut.1.len() < full.1.len(), "NaN corner cut nothing away");
        assert!(cut.1.len() > full.1.len() / 2, "NaN corner removed too much");
        assert!(cut.0.iter().flatten().all(|c| c.is_finite()), "NaN leaked into a vertex");
    }
}
